/**
 * Конфигурация синусоидальной траектории.
 *
 * Точка колеблется перпендикулярно направлению движения несущей (carrier)
 * по закону синуса.
 */
export interface SinWaveConfig {
  /** Амплитуда синусоиды в единицах viewBox (200×150). */
  amplitude: number;
  /** Частота (радиан/сек). */
  frequency: number;
  /** Вектор направления движения несущей. */
  direction: { dx: number; dy: number };
  /** Скорость движения несущей (viewBox-px/сек). */
  speed: number;
  /** Начальная фаза (радиан). */
  phase: number;
}
