/**
 * Конфигурация спиральной траектории.
 *
 * Спираль строится как траектория точки на окружности (кольце),
 * центр которой движется в заданном направлении с постоянной скоростью.
 */
export interface SpiralConfig {
  /** Радиус кольца в единицах viewBox (200×150). */
  radius: number;
  /**
   * Вектор направления смещения центра кольца (единичный или нет —
   * длина нормализуется внутри step()).
   */
  direction: { dx: number; dy: number };
  /** Скорость смещения центра (viewBox-px/сек). */
  speed: number;
  /** Угловая скорость точки на кольце (радиан/сек). */
  angularSpeed: number;
  /** Направление вращения: true — по часовой, false — против. */
  clockwise: boolean;
}
